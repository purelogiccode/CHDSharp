#!/usr/bin/env pwsh
# Generate the winget manifest set for a published GitHub release.
#
# Usage:
#   ./scripts/update-winget-manifests.ps1 -Version 1.7.3
#
# The script reads the Windows bundle URLs and SHA-256 digests from the GitHub
# release API (gh CLI), then writes:
#
#   packaging/winget/manifests/p/PureLogicCode/CHDSharp/<version>/*.yaml
#
# Run it after release.yml has uploaded the six bundles. Older version
# directories are left in place because winget-pkgs keeps every published
# version.

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string] $Version,

    [string] $Repo = 'purelogiccode/CHDSharp'
)

$ErrorActionPreference = 'Stop'

$version = $Version.TrimStart('v')
$repoRoot = Split-Path -Parent $PSScriptRoot
$tag = "v$version"

Write-Host "Reading release $tag from $Repo..."
$release = gh api "repos/$Repo/releases/tags/$tag" | ConvertFrom-Json
$hashes = @{}
foreach ($asset in $release.assets) {
    if ($asset.digest -and $asset.digest.StartsWith('sha256:', [StringComparison]::Ordinal)) {
        $hashes[$asset.name] = $asset.digest.Substring('sha256:'.Length)
    }
}

$winX64Name = "CHDSharp_win-x64_v$version.zip"
$winArm64Name = "CHDSharp_win-arm64_v$version.zip"
foreach ($assetName in @($winX64Name, $winArm64Name)) {
    if (-not $hashes.ContainsKey($assetName)) {
        throw "Release asset $assetName has no SHA-256 digest. Publish the bundles before generating manifests."
    }
}

$winX64 = $hashes[$winX64Name]
$winArm64 = $hashes[$winArm64Name]

$wingetDir = Join-Path $repoRoot "packaging/winget/manifests/p/PureLogicCode/CHDSharp/$version"
New-Item -ItemType Directory -Force -Path $wingetDir | Out-Null

$versionYaml = @"
# Generated by scripts/update-winget-manifests.ps1.
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.version.1.10.0.schema.json
PackageIdentifier: PureLogicCode.CHDSharp
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.10.0
"@

$installerYaml = @"
# Generated by scripts/update-winget-manifests.ps1.
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.installer.1.10.0.schema.json
PackageIdentifier: PureLogicCode.CHDSharp
PackageVersion: $version
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: CHDSharp.exe
    PortableCommandAlias: chdsharp
Installers:
  - Architecture: x64
    InstallerUrl: https://github.com/$Repo/releases/download/$tag/$winX64Name
    InstallerSha256: $($winX64.ToUpperInvariant())
  - Architecture: arm64
    InstallerUrl: https://github.com/$Repo/releases/download/$tag/$winArm64Name
    InstallerSha256: $($winArm64.ToUpperInvariant())
Dependencies:
  PackageDependencies:
    - PackageIdentifier: Microsoft.DotNet.Runtime.11
      MinimumVersion: 11.0.0
ManifestType: installer
ManifestVersion: 1.10.0
"@

$localeYaml = @"
# Generated by scripts/update-winget-manifests.ps1.
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.defaultLocale.1.10.0.schema.json
PackageIdentifier: PureLogicCode.CHDSharp
PackageVersion: $version
PackageLocale: en-US
Publisher: PureLogicCode
PublisherUrl: https://github.com/purelogiccode
PublisherSupportUrl: https://github.com/$Repo/issues
Author: Peterson Fernandes
PackageName: CHDSharp
PackageUrl: https://github.com/$Repo
License: MIT
LicenseUrl: https://github.com/$Repo/blob/main/LICENSE.txt
Copyright: Copyright (c) Peterson Fernandes
ShortDescription: Pure C# CHD reader/writer and chdman-compatible CLI.
Description: A pure C# reader and writer for MAME CHD (Compressed Hunks of Data) disk images. Supports format versions V1-V5, all 10 codecs, parent/child chains, verification, extraction and chdman-compatible creation.
Moniker: chdsharp
Tags:
  - chd
  - mame
  - chdman
  - disk-image
  - emulation
  - compression
ReleaseNotesUrl: https://github.com/$Repo/releases/tag/$tag
ManifestType: defaultLocale
ManifestVersion: 1.10.0
"@

Set-Content -LiteralPath (Join-Path $wingetDir 'PureLogicCode.CHDSharp.yaml') -Value $versionYaml -Encoding utf8NoBOM
Set-Content -LiteralPath (Join-Path $wingetDir 'PureLogicCode.CHDSharp.installer.yaml') -Value $installerYaml -Encoding utf8NoBOM
Set-Content -LiteralPath (Join-Path $wingetDir 'PureLogicCode.CHDSharp.locale.en-US.yaml') -Value $localeYaml -Encoding utf8NoBOM

Write-Host "winget: wrote $wingetDir"
Write-Host "Validate with: winget validate --manifest `"$wingetDir`""
